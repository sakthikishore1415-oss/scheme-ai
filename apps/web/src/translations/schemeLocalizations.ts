/**
 * Strips concatenated slashes from nativeName (e.g. "பிரதமர் கிசான்... / അടൽ...")
 * and extracts the native script matching the language.
 */
function cleanNativeForLanguage(rawNativeName: string, langId: string): string {
  if (!rawNativeName) return '';
  const parts = rawNativeName.split('/').map((s) => s.trim());
  if (parts.length <= 1) return rawNativeName;

  // Language script Unicode ranges
  const scriptRegexMap: Record<string, RegExp> = {
    ta: /[\u0B80-\u0BFF]/,
    ml: /[\u0D00-\u0D7F]/,
    te: /[\u0C00-\u0C7F]/,
    kn: /[\u0C80-\u0CFF]/,
    hi: /[\u0900-\u097F]/,
    bn: /[\u0980-\u09FF]/,
    gu: /[\u0A80-\u0AFF]/,
    or: /[\u0B00-\u0B7F]/,
    pa: /[\u0A00-\u0A7F]/,
    as: /[\u0980-\u09FF]/,
  };

  const reg = scriptRegexMap[langId];
  if (reg) {
    const matched = parts.find((p) => reg.test(p));
    if (matched) return matched;
  }
  return parts[0] || rawNativeName;
}

/**
 * Returns a fully localized Scheme object based on the active language.
 */
export function getLocalizedScheme(scheme: Scheme, languageId: string): Scheme {
  const normLang = (languageId || 'ta').toLowerCase().split('-')[0].split('_')[0];
  if (normLang === 'en') {
    return scheme;
  }

  const loc = SCHEME_LOCALIZATIONS[scheme.id]?.[normLang];
  const cleanedNative = scheme.nativeName ? cleanNativeForLanguage(scheme.nativeName, normLang) : '';

  if (!loc) {
    return {
      ...scheme,
      name: cleanedNative || scheme.name,
      nativeName: cleanedNative || scheme.nativeName,
    };
  }

  return {
    ...scheme,
    name: loc.name || cleanedNative || scheme.name,
    nativeName: cleanedNative || loc.name || scheme.nativeName,
    authority: loc.authority || scheme.authority,
    department: loc.department || scheme.department,
    summarySimple: loc.summarySimple || scheme.summarySimple,
    benefits: {
      ...scheme.benefits,
      amount: loc.benefits?.amount || scheme.benefits?.amount || '',
      frequency: loc.benefits?.frequency || scheme.benefits?.frequency || '',
      type: (loc.benefits?.type || scheme.benefits?.type || 'cash_transfer') as any,
      shortSummary: loc.benefits?.shortSummary || scheme.benefits?.shortSummary || '',
      detailedBenefit: loc.benefits?.detailedBenefit || scheme.benefits?.detailedBenefit || '',
    },
    documents: loc.documents ? loc.documents.map((d) => ({ ...d })) : scheme.documents,
    applicationSteps: loc.applicationSteps || scheme.applicationSteps,
    offlineApplicationCenter: loc.offlineApplicationCenter || scheme.offlineApplicationCenter,
  };
}
